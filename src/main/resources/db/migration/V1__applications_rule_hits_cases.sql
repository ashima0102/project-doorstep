create table loan_application (
    application_id          varchar(64)    primary key,
    applicant_name          varchar(200)   not null,
    dob                     date           not null,
    pan                     varchar(10)    not null,
    phone                   varchar(10)    not null,
    device_id               varchar(100)   not null,
    requested_amount        numeric(14, 2) not null,
    declared_monthly_income numeric(14, 2) not null,
    submitted_at            timestamp with time zone not null,
    decision                varchar(10)    not null,
    score                   integer        not null,
    evaluated_at            timestamp with time zone not null
);

create table rule_hit (
    id             bigint generated by default as identity primary key,
    application_id varchar(64)  not null references loan_application (application_id),
    rule_id        varchar(64)  not null,
    points         integer      not null,
    reason         varchar(500) not null
);

create index idx_rule_hit_application on rule_hit (application_id);

create table fraud_case (
    case_id        uuid        primary key,
    application_id varchar(64) not null unique references loan_application (application_id),
    score          integer     not null,
    decision       varchar(10) not null,
    status         varchar(20) not null,
    created_at     timestamp with time zone not null,
    updated_at     timestamp with time zone not null
);

-- Underwriter queue: list by status, highest score first.
create index idx_fraud_case_status_score on fraud_case (status, score desc, created_at);
