-- Append-only: the application only ever inserts here (no update or delete path exists).
create table case_audit (
    id          bigint generated by default as identity primary key,
    case_id     uuid         not null references fraud_case (case_id),
    from_status varchar(20)  not null,
    to_status   varchar(20)  not null,
    actor       varchar(100) not null,
    comment     varchar(1000) not null,
    at          timestamp with time zone not null
);

create index idx_case_audit_case on case_audit (case_id, at);
